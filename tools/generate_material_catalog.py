def main() -> None:
    CATALOG.mkdir(parents=True, exist_ok=True)
    written = 0
    for item in RECORDS:
        slug = str(item["id"])
        payload = {
            "schema_version": 1,
            "id": f"earth_on_minecraft:{slug}",
            "kind": item["kind"],
            "formula": item["formula"],
            "composition_basis": item["composition_basis"],
            "phase": item["phase"],
        }
        if "molar_mass_g_mol" in item:
            payload["molar_mass_g_mol"] = item["molar_mass_g_mol"]
        payload["constituents"] = item["constituents"]
        payload["source"] = item["source"]
        payload["simplification"] = item["simplification"]
        payload["certainty"] = item["certainty"]
        payload["display_key"] = item["display_key"]
        payload["notes"] = item["notes"]
        out_path = CATALOG / f"{slug}.json"
        out_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        written += 1
    print(f"Generated {written} material catalog records in {CATALOG.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
